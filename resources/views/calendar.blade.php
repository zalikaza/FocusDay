        // Jika tidak ada warna/kategori, pakai abu-abu sebagai default
        if (!rawColor) return '#9ca3af'; // gray-400

        const lower = String(rawColor).trim().toLowerCase();
        const map = {
            'biru': '#2563eb',
            'blue': '#2563eb',
            'hijau': '#10b981',
            'green': '#10b981',
            'kuning': '#f59e0b',
            'yellow': '#f59e0b',
            'merah': '#ef4444',
            'red': '#ef4444',
            'ungu': '#7c3aed',
