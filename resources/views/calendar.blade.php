            'pink': '#ec4899',
            'abu-abu': '#9ca3af',
            'gray': '#9ca3af',
            'grey': '#9ca3af',
        };
        // Kalau warna dikenali di map → pakai itu, kalau tidak → pakai nilai aslinya
        // (fallback terakhir tetap abu-abu kalau entah kenapa masih falsy)
        return map[lower] || rawColor || '#9ca3af';
